-- Initial schema of order-service.
-- Matches the DDL Hibernate generated from the JPA entities (CartItem, Order, OrderItem),
-- so that spring.jpa.hibernate.ddl-auto=validate passes.

create table cart_item (
    id         bigint generated by default as identity,
    user_id    bigint,
    product_id bigint,
    quantity   integer,
    price      numeric(38, 2),
    created_at timestamp(6),
    updated_at timestamp(6),
    primary key (id),
    constraint uk_cart_item_user_product unique (user_id, product_id)
);

create table orders (
    id           bigint generated by default as identity,
    user_id      bigint,
    status       varchar(255)
        check (status in ('PENDING', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    total_amount numeric(38, 2),
    created_at   timestamp(6),
    updated_at   timestamp(6),
    primary key (id)
);

create table order_item (
    id         bigint generated by default as identity,
    order_id   bigint not null,
    product_id bigint,
    quantity   integer,
    price      numeric(38, 2),
    primary key (id),
    constraint fk_order_item_order foreign key (order_id) references orders (id)
);
